#!/usr/bin/env bash
set -euo pipefail

#
# bootstrap-state.sh — One-time setup of the Terraform remote state backend (PETPLAT-2)
#
# Creates (or brings into compliance) the resources Terraform needs before
# `terraform init`, per docs/technical-spec.md#terraform-state-backend:
#   - S3 bucket  petclinic-terraform-state-{account-id}
#       versioning on, SSE AES256, all 4 public-access blocks, TLS-only policy,
#       bucket-owner-enforced ownership (ACLs disabled)
#
# No DynamoDB table is created: the backend uses Terraform's native S3 locking
# (use_lockfile = true, Terraform >= 1.10), which stores a .tflock object next
# to each state file in this same bucket.
#
# Idempotent: existing resources are detected and their settings re-applied.
# Also writes terraform/environments/{dev,prod}/backend.hcl with the bucket name.
#
# Usage:
#   ./scripts/bootstrap-state.sh                       # region ap-south-1
#   ./scripts/bootstrap-state.sh --region eu-west-1
#
# Requires: aws CLI v2, credentials with S3 + STS permissions.
#

REGION="ap-south-1"
PROJECT="petproject"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_DIR="${SCRIPT_DIR}/../terraform/environments"

usage() {
  echo "Usage: $0 [--region <aws-region>]"
  echo ""
  echo "  --region   AWS region for the state bucket (default: ap-south-1)"
  echo "  -h|--help  Show this help"
  exit "${1:-0}"
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --region)
      [[ $# -ge 2 && -n "$2" ]] || { echo "Error: --region requires a value"; usage 1; }
      REGION="$2"; shift 2 ;;
    --region=*)
      REGION="${1#*=}"; shift ;;
    -h|--help)
      usage 0 ;;
    *)
      echo "Error: unknown argument '$1'"; usage 1 ;;
  esac
done

command -v aws >/dev/null 2>&1 || { echo "Error: aws CLI not found in PATH"; exit 1; }

echo "==> Verifying AWS credentials"
ACCOUNT_ID="$(aws sts get-caller-identity --query Account --output text)"
BUCKET_NAME="${PROJECT}-terraform-state-${ACCOUNT_ID}"
TAGS_S3="TagSet=[{Key=Project,Value=${PROJECT}},{Key=Environment,Value=shared},{Key=ManagedBy,Value=bootstrap-state.sh}]"

echo "    Account: ${ACCOUNT_ID}"
echo "    Region:  ${REGION}"
echo "    Bucket:  ${BUCKET_NAME}"

# ---------------------------------------------------------------------------
# S3 bucket
# ---------------------------------------------------------------------------
echo "==> S3 bucket"
if aws s3api head-bucket --bucket "${BUCKET_NAME}" 2>/dev/null; then
  echo "    Exists, re-applying settings"
else
  echo "    Creating"
  if [[ "${REGION}" == "us-east-1" ]]; then
    aws s3api create-bucket --bucket "${BUCKET_NAME}" --region "${REGION}" >/dev/null
  else
    aws s3api create-bucket --bucket "${BUCKET_NAME}" --region "${REGION}" \
      --create-bucket-configuration "LocationConstraint=${REGION}" >/dev/null
  fi
  aws s3api wait bucket-exists --bucket "${BUCKET_NAME}"
fi

echo "    Blocking all public access"
aws s3api put-public-access-block --bucket "${BUCKET_NAME}" \
  --public-access-block-configuration \
  "BlockPublicAcls=true,IgnorePublicAcls=true,BlockPublicPolicy=true,RestrictPublicBuckets=true"

echo "    Disabling ACLs (BucketOwnerEnforced)"
aws s3api put-bucket-ownership-controls --bucket "${BUCKET_NAME}" \
  --ownership-controls 'Rules=[{ObjectOwnership=BucketOwnerEnforced}]'

echo "    Enabling versioning"
aws s3api put-bucket-versioning --bucket "${BUCKET_NAME}" \
  --versioning-configuration Status=Enabled

echo "    Enabling default encryption (AES256)"
aws s3api put-bucket-encryption --bucket "${BUCKET_NAME}" \
  --server-side-encryption-configuration \
  '{"Rules":[{"ApplyServerSideEncryptionByDefault":{"SSEAlgorithm":"AES256"},"BucketKeyEnabled":true}]}'

echo "    Enforcing TLS-only access"
aws s3api put-bucket-policy --bucket "${BUCKET_NAME}" --policy "{
  \"Version\": \"2012-10-17\",
  \"Statement\": [{
    \"Sid\": \"DenyInsecureTransport\",
    \"Effect\": \"Deny\",
    \"Principal\": \"*\",
    \"Action\": \"s3:*\",
    \"Resource\": [\"arn:aws:s3:::${BUCKET_NAME}\", \"arn:aws:s3:::${BUCKET_NAME}/*\"],
    \"Condition\": {\"Bool\": {\"aws:SecureTransport\": \"false\"}}
  }]
}"

echo "    Tagging"
aws s3api put-bucket-tagging --bucket "${BUCKET_NAME}" --tagging "${TAGS_S3}"

# ---------------------------------------------------------------------------
# Backend partial config for each environment
# ---------------------------------------------------------------------------
echo "==> Writing backend.hcl files"
for env in dev prod; do
  if [[ -d "${ENV_DIR}/${env}" ]]; then
    printf '# Generated by scripts/bootstrap-state.sh — do not commit\nbucket = "%s"\nregion = "%s"\n' \
      "${BUCKET_NAME}" "${REGION}" > "${ENV_DIR}/${env}/backend.hcl"
    echo "    terraform/environments/${env}/backend.hcl"
  fi
done

echo ""
echo "Done. Next:"
echo "  cd terraform/environments/dev && terraform init -backend-config=backend.hcl"
